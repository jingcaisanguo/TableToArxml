_DECLARED_ENCODING = re.compile(rb"""^<\?xml[^>]*?encoding\s*=\s*["']([A-Za-z0-9._-]+)["']""")
_PROLOG_ITEM = re.compile(r"\s*(?:<\?.*?\?>|<!--.*?-->|<!DOCTYPE(?:[^\[>]|\[.*?\])*>)", re.DOTALL)
_NAMESPACE_DECLARATION = re.compile(r"""xmlns:([A-Za-z_][\w.-]*)\s*=\s*(["'])(.*?)\2""")


def _tag(name: str) -> str:
    return f"{{{NAMESPACE}}}{name}"


def _kind(element: ET.Element) -> str:
    """Local tag name; empty for comments and processing instructions."""

    return element.tag.rsplit("}", 1)[-1] if isinstance(element.tag, str) else ""


def _name(element: ET.Element) -> str:
    return element.findtext("ar:SHORT-NAME", default="", namespaces=NS)


def _elements(parent: ET.Element) -> list[ET.Element]:
    return [child for child in parent if isinstance(child.tag, str)]


def _has_variation_point(element: ET.Element) -> bool:
    return element.find("ar:VARIATION-POINT", NS) is not None


def _index(root: ET.Element) -> dict[str, ET.Element]:
    result: dict[str, ET.Element] = {}

    def visit(element: ET.Element, parent: str) -> None:
        name = _name(element)
        path = f"{parent}/{name}" if name else parent
        if name:
            if path in result:
                # Variant-rich models may hold several elements with one path under different VARIATION-POINTs.
                if _has_variation_point(result[path]) and _has_variation_point(element):
                    return
                raise ValueError(f"Duplicate AUTOSAR path in merge document: {path}")
            result[path] = element
        for child in _elements(element):
            visit(child, path)

    visit(root, "")
    return result


@dataclass
class _Document:
    """Parsed ARXML plus the byte-level details ElementTree drops: prolog, epilog, encoding and newline style."""

    tree: ET.ElementTree
    index: dict[str, ET.Element]
    encoding: str = "utf-8"
    bom: bytes = b""
    prolog: str = ""
    epilog: str = ""
    newline: str = "\n"
    namespaces: tuple[tuple[str, str], ...] = ()


def _encoding(raw: bytes) -> tuple[str, bytes]:
    if raw.startswith(codecs.BOM_UTF8):
        return "utf-8", codecs.BOM_UTF8
    if raw.startswith(codecs.BOM_UTF16_LE):
        return "utf-16-le", codecs.BOM_UTF16_LE
    if raw.startswith(codecs.BOM_UTF16_BE):
        return "utf-16-be", codecs.BOM_UTF16_BE
    match = _DECLARED_ENCODING.match(raw[:256])
    return (match.group(1).decode("ascii") if match else "utf-8"), b""


def _prolog_end(text: str) -> int:
    position = 0
    while True:
        match = _PROLOG_ITEM.match(text, position)
        if match is None:
            break
        position = match.end()
    while position < len(text) and text[position].isspace():
        position += 1
    return position


def _epilog_start(text: str) -> int:
    end = len(text)
    while True:
        while end and text[end - 1].isspace():
            end -= 1
        for opening, closing in (("<!--", "-->"), ("<?", "?>")):
            if text.endswith(closing, 0, end):
                start = text.rfind(opening, 0, end)
                if start >= 0:
                    end = start
                    break
        else:
            return end


def _normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _read(path: Path) -> _Document:
    try:
        raw = path.read_bytes()
        parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True, insert_pis=True))
        parser.feed(raw)
        root = parser.close()
        encoding, bom = _encoding(raw)
        text = raw[len(bom):].decode(encoding)
    except (ET.ParseError, LookupError, UnicodeError, ValueError) as error:
        raise ValueError(f"Cannot parse ARXML for base merge ({path}): {error}") from error
    if root.tag != _tag("AUTOSAR"):
        raise ValueError(f"Base ARXML must use the AUTOSAR r4.0 namespace: {path}")
    prolog_end = _prolog_end(text)
    root_start = text[prolog_end:text.find(">", prolog_end) + 1]
    crlf = text.count("\r\n")
    return _Document(
        tree=ET.ElementTree(root), index=_index(root), encoding=encoding, bom=bom,
        prolog=_normalize_newlines(text[:prolog_end]),
        epilog=_normalize_newlines(text[max(_epilog_start(text), prolog_end):]),
        newline="\r\n" if crlf and crlf * 2 >= text.count("\n") else "\n",
        namespaces=tuple((prefix, uri) for prefix, _, uri in _NAMESPACE_DECLARATION.findall(root_start)),
    )


def _parse(path: Path) -> ET.ElementTree:
    return _read(path).tree


def _write(document: _Document, path: Path) -> None:
    """Serialize with the base's prolog, encoding and newline style; unchanged elements keep their whitespace."""

    for prefix, uri in document.namespaces:
        try:
            ET.register_namespace(prefix, uri)
        except ValueError:
            pass
    ET.register_namespace("", NAMESPACE)
    ET.register_namespace("xsi", XSI_NAMESPACE)
    text = document.prolog + ET.tostring(document.tree.getroot(), encoding="unicode") + document.epilog
    if document.newline != "\n":
        text = text.replace("\n", document.newline)
    path.write_bytes(document.bom + text.encode(document.encoding, "xmlcharrefreplace"))


def prepare_base_model(base_file: Path, model_file: Path, document: AUTOSAR) -> tuple[Path, frozenset[str]]:
    """Expose base definitions to resolution without treating its mappings as external splits."""

    tree = _parse(base_file)
    base = _index(tree.getroot())
    for path, item in base.items():
        if item.tag in {_tag("SYSTEM-MAPPING"), _tag("PORT-INTERFACE-MAPPING-SET")} and document.find(path) is not None:
            raise ValueError(f"Cannot split existing {item.tag.rsplit('}', 1)[-1]} while merging base: {path}")
    for owner in tree.getroot().iter():
        if owner.tag == _tag("COMPOSITION-SW-COMPONENT-TYPE"):
            container = owner.find("ar:CONNECTORS", NS)
        elif owner.tag == _tag("SYSTEM"):
            container = owner.find("ar:MAPPINGS", NS)
        else:
            continue
        if container is not None:
            owner.remove(container)
    model_file.parent.mkdir(parents=True, exist_ok=True)
    tree.write(model_file, encoding="utf-8", xml_declaration=True)
    return model_file, frozenset(
        path for path, item in base.items() if item.tag == _tag("PORT-INTERFACE-MAPPING-SET"))


class _References:
    """Resolves base references, including relative ones that use a REFERENCE-BASE of an enclosing AR-PACKAGE."""

    def __init__(self, parents: dict[ET.Element, ET.Element]) -> None:
        self.parents = parents

    def path(self, reference: ET.Element) -> Optional[str]:
        text = (reference.text or "").strip()
        if text.startswith("/"):
            return text
        label = reference.get("BASE")
        owner = self.parents.get(reference)
        while owner is not None:
            if owner.tag == _tag("AR-PACKAGE"):
                for base in owner.findall("ar:REFERENCE-BASES/ar:REFERENCE-BASE", NS):
                    selected = (base.findtext("ar:SHORT-LABEL", default="", namespaces=NS).strip() == label
                                if label else
                                base.findtext("ar:IS-DEFAULT", default="", namespaces=NS).strip() == "true")
                    package = base.findtext("ar:PACKAGE-REF", default="", namespaces=NS).strip()
                    if selected and package.startswith("/"):
                        return f"{package.rstrip('/')}/{text}" if text else None
            owner = self.parents.get(owner)
        return None

    def text(self, reference: ET.Element) -> str:
        return self.path(reference) or (reference.text or "").strip()


def _is_reference(element: ET.Element) -> bool:
    return not len(element) and _kind(element).endswith(("-REF", "-TREF"))


def _references(element: ET.Element) -> Iterator[ET.Element]:
    """Leaf references of a subtree outside descriptions, admin data, variation points and type mappings."""

    if _kind(element) in UNCHECKED_SUBTREES:
        return
    if _is_reference(element):
        yield element
        return
    for child in _elements(element):
        yield from _references(child)


def _identifying_references(element: ET.Element) -> Iterator[tuple[str, ET.Element]]:
    for child in _elements(element):
        kind = _kind(child)
        if kind in IDENTITY.get(_kind(element), ()):
            for reference in _references(child):
                yield kind, reference


def _identity(element: ET.Element, references: _References) -> tuple:
    leaves = sorted(
        ((role, _kind(reference), references.text(reference))
         for role, reference in _identifying_references(element)),
        key=lambda leaf: leaf[:2])
    return _kind(element), tuple(leaves)


def _describe(identity: tuple) -> str:
    return ", ".join(f"{kind}={path}" for _, kind, path in identity[1]) or "(no references)"


def _child_text(element: ET.Element, kind: str) -> str:
    return (element.findtext(f"ar:{kind}", default="", namespaces=NS) or "").strip()


def _compatible(existing: ET.Element, request: ET.Element) -> bool:
    """Generated fields must agree; base-only metadata is not an update request."""

    if existing.tag != request.tag or (existing.text or "").strip() != (request.text or "").strip():
        return False
    if any(existing.get(key) != value for key, value in request.attrib.items()):
        return False
    remaining = _elements(existing)
    for child in _elements(request):
        match = next((item for item in remaining if _compatible(item, child)), None)
        if match is None:
            return False
        remaining.remove(match)
    return True


class _Peers:
    """Base connectors or signal mappings indexed once by identity and name."""

    def __init__(self, items: Iterable[ET.Element], context: str, references: _References) -> None:
        self.context = context
        self.references = references
        self.by_identity: dict[tuple, ET.Element] = {}
        self.by_name: dict[str, ET.Element] = {}
        self.folded: dict[str, str] = {}
        for item in items:
            self.add(item)

    def add(self, item: ET.Element) -> None:
        self.by_identity.setdefault(_identity(item, self.references), item)
        name = _name(item)
        if name:
            self.by_name.setdefault(name, item)
            self.folded.setdefault(name.casefold(), name)

    def reuse(self, request: ET.Element) -> bool:
        """True when the base already holds the requested object; conflicting objects raise ``ValueError``."""

        identity = _identity(request, self.references)
        name = _name(request)
        existing = self.by_identity.get(identity)
        if existing is not None:
            if _kind(request) in SIGNAL_MAPPINGS:
                self._check_signal_mapping(existing, request, identity)
                LOGGER.info("Reuse base signal mapping in %s: %s", self.context, _describe(identity))
            else:
                self._check_connector(existing, request)
            return True
        if name in self.by_name:
            other = _identity(self.by_name[name], self.references)
            raise ValueError(
                f"Conflicting base connector {self.context}/{name}: base connects {_describe(other)}; "
                f"table requests {_describe(identity)}")
        other_name = self.folded.get(name.casefold()) if name else None
        if other_name:
            LOGGER.warning("%s: base name %s differs only in case from %s", self.context, other_name, name)
        return False

    def _check_signal_mapping(self, existing: ET.Element, request: ET.Element, identity: tuple) -> None:
        # COMMUNICATION-DIRECTION is optional (removed in R23-11); a base mapping without it is compatible.
        current, requested = _child_text(existing, "COMMUNICATION-DIRECTION"), _child_text(
            request, "COMMUNICATION-DIRECTION")
        if current and requested and current != requested:
            raise ValueError(
                f"Conflicting base signal mapping in {self.context}: {_describe(identity)}: base "
                f"COMMUNICATION-DIRECTION {current}, table requests {requested}")

    def _check_connector(self, existing: ET.Element, request: ET.Element) -> None:
        name, base_name = _name(request), _name(existing)
        if name == base_name:
            LOGGER.info("Reuse duplicate base connector: %s/%s", self.context, name)
        else:
            LOGGER.info("Reuse base connector %s/%s for table connector %s", self.context, base_name, name)
        requested = _child_text(request, "MAPPING-REF")
        reference = existing.find("ar:MAPPING-REF", NS)
        current = "" if reference is None else self.references.text(reference)
        if requested and current != requested:
            LOGGER.warning(
                "%s: base connector %s is reused but references interface mapping %s instead of %s; "
                "add the mapping to the connector manually if it is required",
                self.context, base_name, current or "(none)", requested)


class _Layout:
    """Indents inserted subtrees like their new siblings; base whitespace is never rewritten."""

    def __init__(self, root: ET.Element, parents: dict[ET.Element, ET.Element]) -> None:
        self.parents = parents
        self.unit = self._unit(root)

    @staticmethod
    def _unit(root: ET.Element) -> Optional[str]:
        if "\n" not in (root.text or ""):
            return None
        element, own = root, ""
        while True:
            children = _elements(element)
            text = element.text or ""
            if not children or "\n" not in text or text.strip():
                return "  "
            child = text.rsplit("\n", 1)[1]
            if len(child) > len(own) and child.startswith(own):
                return child[len(own):]
            element, own = children[0], child

    def leading(self, element: ET.Element) -> Optional[str]:
        parent = self.parents.get(element)
        if parent is None:
            return None
        siblings = list(parent)
        index = next(index for index, item in enumerate(siblings) if item is element)
        whitespace = parent.text if index == 0 else siblings[index - 1].tail
        if _is_indent(whitespace):
            return whitespace
        depth, owner = 0, element
        while owner in self.parents:
            depth, owner = depth + 1, self.parents[owner]
        return "\n" + self.unit * depth

    def insert(self, parent: ET.Element, child: ET.Element) -> ET.Element:
        retained = deepcopy(child)
        retained.tail = None
        siblings = list(parent)
        position = _position(parent, _kind(child), siblings)
        indent: Optional[str] = None
        if self.unit is not None:
            if position < len(siblings):
                before = parent.text if position == 0 else siblings[position - 1].tail
                retained.tail = before
                indent = before
            elif siblings:
                before = parent.text if len(siblings) == 1 else siblings[-2].tail
                retained.tail = siblings[-1].tail
                siblings[-1].tail = before
                indent = before
            else:
                closing = parent.text if _is_indent(parent.text) else self.leading(parent)
                if closing is not None:
                    indent = closing + self.unit
                    parent.text = indent
                    retained.tail = closing
        if _is_indent(indent):
            _reindent(retained, indent, self.unit)
        else:
            _compact(retained)
        parent.insert(position, retained)
        return retained


def _is_indent(value: Optional[str]) -> bool:
    return value is not None and "\n" in value and not value.strip()


def _reindent(element: ET.Element, indent: str, unit: str) -> None:
    children = list(element)
    if not children:
        return
    inner = indent + unit
    if not (element.text or "").strip():
        element.text = inner
    for child in children:
        _reindent(child, inner, unit)
        if not (child.tail or "").strip():
            child.tail = inner
    if not (children[-1].tail or "").strip():
        children[-1].tail = indent


def _compact(element: ET.Element) -> None:
    for item in element.iter():
        if len(item) and not (item.text or "").strip():
            item.text = None
        if item is not element and not (item.tail or "").strip():
            item.tail = None


def _position(parent: ET.Element, kind: str, siblings: list[ET.Element]) -> int:
    """Index before the first sibling that the AUTOSAR schema orders after ``kind``."""

    order = CHILD_ORDER.get(_kind(parent))
    if order is None or kind not in order:
        return len(siblings)
    rank = order[kind]
    return next((index for index, sibling in enumerate(siblings)
                 if order.get(_kind(sibling), -1) > rank), len(siblings))


@dataclass
class _MergeState:
    layout: _Layout
    references: _References
    added: list[ET.Element]

    def key(self, element: ET.Element) -> tuple:
        return tuple(sorted(((_kind(reference), self.references.text(reference))
                             for reference in _references(element)), key=lambda leaf: leaf[0]))


def _merge(target: ET.Element, source: ET.Element, path: str, state: _MergeState) -> None:
    allowed = MERGE_CHILDREN.get(_kind(source))
    named: dict[str, ET.Element] = {}
    unnamed: dict[str, ET.Element] = {}
    for item in _elements(target):
        name = _name(item)
        if name:
            named.setdefault(name, item)
        else:
            unnamed.setdefault(item.tag, item)
    listed: dict[str, set[tuple]] = {}
    for child in _elements(source):
        child_kind = _kind(child)
        if allowed is not None and child_kind not in allowed:
            continue
        name = _name(child)
        context = f"{path}/{name}" if name else path
        if child_kind in IDENTITY:
            # Connectors and signal mappings were deduplicated against the base before merging.
            state.added.append(state.layout.insert(target, child))
            continue
        nested = child_kind in CONTAINERS or child_kind in MERGE_CHILDREN
        if not name and not nested:
            # Unnamed list items such as COMPONENT-IREF and FIBEX-ELEMENT-REF-CONDITIONAL.
            keys = listed.get(child.tag)
            if keys is None:
                keys = listed[child.tag] = {state.key(item) for item in _elements(target) if item.tag == child.tag}
            key = state.key(child)
            if key not in keys:
                keys.add(key)
                state.added.append(state.layout.insert(target, child))
            continue
        existing = named.get(name) if name else unnamed.get(child.tag)
        if existing is None:
            inserted = state.layout.insert(target, child)
            state.added.append(inserted)
            if name:
                named[name] = inserted
            else:
                unnamed[child.tag] = inserted
            continue
        if existing.tag != child.tag:
            raise ValueError(f"Conflicting base object: {context}")
        if child_kind == "SWC-TO-ECU-MAPPING" and _child_text(existing, "ECU-INSTANCE-REF") != _child_text(
                child, "ECU-INSTANCE-REF"):
            raise ValueError(f"Conflicting base ECU mapping: {context}")
        if nested:
            _merge(existing, child, context, state)
        elif not _compatible(existing, child):
            raise ValueError(f"Conflicting base object: {context}")


def _parents(root: ET.Element) -> dict[ET.Element, ET.Element]:
    return {child: parent for parent in root.iter() for child in parent}


def _deduplicate_connectors(base: dict[str, ET.Element], generated: dict[str, ET.Element],
                            references: _References) -> None:
    for path, composition in generated.items():
        connectors = composition.find("ar:CONNECTORS", NS)
        base_composition = base.get(path)
        if (composition.tag != _tag("COMPOSITION-SW-COMPONENT-TYPE") or connectors is None
                or base_composition is None or base_composition.tag != composition.tag):
            continue
        peers = _Peers(base_composition.findall("ar:CONNECTORS/*", NS), path, references)
        for connector in _elements(connectors):
            if peers.reuse(connector):
                connectors.remove(connector)
            else:
                peers.add(connector)


def _deduplicate_signal_mappings(system: ET.Element, generated_system: Optional[ET.Element], system_path: str,
                                 references: _References) -> None:
    # Signal mappings have no SHORT-NAME and can already exist under another SystemMapping.
    if generated_system is None:
        return
    peers = _Peers(
        (item for item in system.findall("ar:MAPPINGS/ar:SYSTEM-MAPPING/ar:DATA-MAPPINGS/*", NS)
         if _kind(item) in SIGNAL_MAPPINGS), system_path, references)
    for data in generated_system.findall("ar:MAPPINGS/ar:SYSTEM-MAPPING/ar:DATA-MAPPINGS", NS):
        for item in _elements(data):
            if _kind(item) not in SIGNAL_MAPPINGS:
                continue
            if peers.reuse(item):
                data.remove(item)
            else:
                peers.add(item)


def _drop_unreferenced_interface_mappings(generated_root: ET.Element) -> None:
    """A reused base connector keeps its own mapping, so a generated mapping only it needed is not written."""

    referenced = {(item.text or "").strip() for item in generated_root.iter(_tag("MAPPING-REF"))}
    for path, mapping_set in _index(generated_root).items():
        container = mapping_set.find("ar:PORT-INTERFACE-MAPPINGS", NS)
        if mapping_set.tag != _tag("PORT-INTERFACE-MAPPING-SET") or container is None:
            continue
        for mapping in _elements(container):
            if f"{path}/{_name(mapping)}" not in referenced:
                LOGGER.info("Interface mapping %s/%s is not written; no added connector references it",
                            path, _name(mapping))
                container.remove(mapping)


def _drop_empty(root: ET.Element) -> None:
    parents = _parents(root)
    for element in reversed(list(root.iter())):
        kind = _kind(element)
        children = _elements(element)
        empty = (kind in CONTAINERS and not children) or (
            kind in EMPTY_WITH_NAME_ONLY and all(child.tag == _tag("SHORT-NAME") for child in children))
        if empty and element in parents:
            parents[element].remove(element)


def _validate(items: Iterable[ET.Element], identifying_only: bool, merged: dict[str, ET.Element],
              document: AUTOSAR, references: _References) -> None:
    for item in items:
        if identifying_only:
            leaves: Iterable[ET.Element] = (reference for _, reference in _identifying_references(item))
        else:
            leaves = _references(item)
        for reference in leaves:
            path = references.path(reference)
            if path is None:
                LOGGER.warning(
                    "Cannot resolve relative reference %s (BASE=%s) in %s; it is not validated",
                    (reference.text or "").strip(), reference.get("BASE") or "default", _name(item) or _kind(item))
                continue
            autosar_path(path, "Base connection or signal mapping reference")
            target = merged.get(path)
            if target is not None:
                destination = _kind(target)
            else:
                existing = document.find(path)
                if existing is None:
                    raise ValueError(f"Base connection or signal mapping references missing object: {path}")
                destination = class_destination(existing)
            if reference.get("DEST") != destination:
                raise ValueError(f"Base reference {path} has DEST={reference.get('DEST')!r}; expected {destination}")


def merge_base_arxml(
    output_file: Path, base_file: Path, document: AUTOSAR, composition_path: str, system_path: str,
) -> None:
    """Preserve the entire base and append generated objects before atomic publication.

    An empty ``system_path`` means that no System is merged: generated System content is ignored and base signal
    mappings are neither deduplicated nor validated.
    """

    LOGGER.info("Adding table objects to complete base ARXML: %s", base_file)
    source = _read(base_file)
    root = source.tree.getroot()
    generated_root = _read(output_file).tree.getroot()
    base = source.index
    parents = _parents(root)
    references = _References(parents)
    if not system_path:
        generated_parents = _parents(generated_root)
        for item in list(generated_root.iter(_tag("SYSTEM"))):
            generated_parents[item].remove(item)
    generated = _index(generated_root)
    _deduplicate_connectors(base, generated, references)
    system = base.get(system_path) if system_path else None
    if system is not None:
        _deduplicate_signal_mappings(system, generated.get(system_path), system_path, references)
    _drop_unreferenced_interface_mappings(generated_root)
    _drop_empty(generated_root)
    for path, item in _index(generated_root).items():
        if item.tag in {_tag("SYSTEM-MAPPING"), _tag("PORT-INTERFACE-MAPPING-SET")}:
            if path not in base and document.find(path) is not None:
                raise ValueError(f"Cannot split existing {item.tag.rsplit('}', 1)[-1]} while merging base: {path}")
    state = _MergeState(_Layout(root, parents), references, [])
    _merge(root, generated_root, "", state)
    merged = _index(root)
    _validate(state.added, False, merged, document, references)
    composition = base.get(composition_path)
    if composition is not None:
        _validate(composition.findall("ar:CONNECTORS/*", NS), True, merged, document, references)
    if system is not None:
        _validate((item for item in system.findall("ar:MAPPINGS/ar:SYSTEM-MAPPING/ar:DATA-MAPPINGS/*", NS)
                   if _kind(item) in SIGNAL_MAPPINGS), True, merged, document, references)
    _write(source, output_file)
    LOGGER.info("Preserved complete base and added %s table subtrees -> %s", len(state.added), output_file)
